using UnityEngine;
using System;
using System.IO;

public class FileDataManager
{
    private string dataDirectoryPath = "";
    private string dataFileName = "";

    // this is the constructor of this class, but unlike other constructor, this takes two arguments
    // just like other constrcutors, this allows us to create instances of this class with data pre-loaded
    public FileDataManager(string dataDirPath, string dataFName)
    {
        this.dataDirectoryPath = dataDirPath;
        this.dataFileName = dataFName;
    }

    public GameData LoadFile()
    {
        GameData loadedData = null;

        return loadedData;
    }

    public void SaveFile(GameData data)
    {
        //this string is the directory path on our local machine
        //it is being generated by the "dataDirectoryPath" and "dataFileName" variables
        //this of this like writing "Desktop\Folder\Data" + "fileName"
        string fullPathToFile = Path.Combine(dataDirectoryPath, dataFileName);

        //try/catch are a type of logic that allows you to create non-conditional breaks in your code
        //the below code is attempted to be executed, but if any error occur, the logic of "try" breaks
        //and the catch "reports" the exception error in a Debug.LogError
        try
        {
            //Creates the file & directory at the location we specified in the string "fullPathToFile"
            Directory.CreateDirectory(Path.GetDirectoryName(fullPathToFile));

            //dataToStore is the serialized data from our GameData argument, and "prettyPrint" organized as a string
            //this will be written into our file on our local machine
            string dataToStore = JsonUtility.ToJson(data, true);

            //`using` is a type of logic where the condition checks to make sure whatever System.IO class that is being opened
            //is then safely closed if any errors occur in the process within that logic block
            //this will prevent data leaks in your software!
            using (FileStream stream = new FileStream(fullPathToFile, FileMode.Create))
            {
                using (StreamWriter writer = new StreamWriter(stream))
                {
                    writer.Write(dataToStore);
                }
            }
        }
        catch(Exception e)
        {
            Debug.LogError("Path does not exist: " + fullPathToFile + "\n" + e);
        }
    }
}
